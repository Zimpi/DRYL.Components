namespace DRYL.Components;

/// <summary>Where a <see cref="DrylPopover"/> panel opens relative to its trigger.</summary>
public enum PopoverPlacement
{
    /// <summary>Below the trigger, left-aligned.</summary>
    BottomStart,
    /// <summary>Below the trigger, right-aligned.</summary>
    BottomEnd,
    /// <summary>Above the trigger, left-aligned.</summary>
    TopStart,
    /// <summary>Above the trigger, right-aligned.</summary>
    TopEnd
}
